Theme.SurfaceThemes = ShopTheme.SurfaceThemes

function Theme.getSurfaceTheme(themeKey)
	return ShopTheme.getSurfaceTheme(themeKey)
end

function Theme.getCategorySurface(category)
	local themeKey = category and category.themeKey or "Cyan"
	return Theme.getSurfaceTheme(themeKey)
end

function Theme.getRarityStyle(rarityName)
	return Theme.RarityStyles[tostring(rarityName or "")] or Theme.RarityStyles.Common
end

